BY_ID: dict[str, Rule] = {rule.id: rule for rule in RULES}

CATEGORIES: dict[str, str] = {
    PROTOCOL: "protocol versions the server is willing to speak",
    CIPHER: "cipher suites the server is willing to use",
    CERTIFICATE: "what the certificate itself says",
    TRANSPORT: "how the site behaves around the TLS connection",
}


def rules_for(category: str | None = None, severity: str | None = None) -> list[Rule]:
    out = RULES
    if category:
        out = [r for r in out if r.category == category]
    if severity:
        out = [r for r in out if r.severity == severity]
    return out


def get(rule_id: str) -> Rule:
    return BY_ID[rule_id]
